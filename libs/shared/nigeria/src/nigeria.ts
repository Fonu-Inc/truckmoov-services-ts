// A floor, not proof: only meant to reject coordinates that are clearly abroad.
export const NIGERIA_BBOX = { minLat: 4.2, maxLat: 13.9, minLng: 2.6, maxLng: 14.7 } as const;

export function isInsideNigeria(lat: unknown, lng: unknown): boolean {
  return (
    typeof lat === 'number' &&
    typeof lng === 'number' &&
    Number.isFinite(lat) &&
    Number.isFinite(lng) &&
    lat >= NIGERIA_BBOX.minLat &&
    lat <= NIGERIA_BBOX.maxLat &&
    lng >= NIGERIA_BBOX.minLng &&
    lng <= NIGERIA_BBOX.maxLng
  );
}

const fold = (raw: unknown): string =>
  String(raw ?? '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]/gu, '');

const STATE_BY_KEY = new Map<string, string>(
  NIGERIAN_STATES.map((state) => [fold(state), state]),
);
for (const alias of ['Federal Capital Territory', 'Abuja', 'Abuja (FCT)'])
  STATE_BY_KEY.set(fold(alias), 'FCT');

export function normalizeNigerianState(raw: unknown): string | null {
  const key = fold(raw);
  return STATE_BY_KEY.get(key.endsWith('state') ? key.slice(0, -5) : key) ?? null;
}

export function lgasOf(state: string): readonly string[] {
  const canonical = normalizeNigerianState(state);
  return canonical ? LGAS_BY_STATE[canonical] : [];
}

export function canonicalLga(state: string, raw: unknown): string | null {
  const key = fold(raw);
  if (!key) return null;
  return lgasOf(state).find((lga) => fold(lga) === key) ?? null;
}

export function normalizeCountry(raw: unknown): 'Nigeria' | null {
  const key = fold(raw);
  return key === 'nigeria' || key === 'ng' || key === 'nga' ? 'Nigeria' : null;
}

const PLACE_NAMES = [
  ...NIGERIAN_STATES,
  'Nigeria',
  'Federal Capital Territory',
  'Abuja',
  ...Object.values(LGAS_BY_STATE).flat(),
];
const escapeRegex = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const PLACE_PATTERN = new RegExp(
  `(?<![\\p{L}\\p{N}])(?:${[...new Set(PLACE_NAMES.map((name) => name.toLowerCase()))]
    .sort((a, b) => b.length - a.length)
    .map(escapeRegex)
    .join('|')})(?![\\p{L}\\p{N}])`,
  'u',
);

/** True when a free-text address names a Nigerian state, LGA, Abuja or Nigeria itself. */
export function mentionsNigerianPlace(raw: unknown): boolean {
  return PLACE_PATTERN.test(String(raw ?? '').toLowerCase());
}

